putaran = 5
jarak = 14
pi = 3.14

keliling = jarak / putaran
jari_jari = float(keliling / (2 * pi))

print("Diketahui : Pak Dengklek mengelilingi taman = %d Putaran" % putaran)
print("Jarak tempuh Pak Dengklek = %d Kilometer" % jarak)
print("Jawaban : Jari-jari taman yang dikelilingi Pak Dengklek adalah %.2f Kilometer." % jari_jari)